-- Step 13: ONE QUERY PER SCENARIO. Run each query TWICE:
--   BEFORE the job (now)  -> screenshot = "Before"
--   AFTER  the job        -> screenshot = "After"
-- Deal 2001371316, old txn = 5, new txn = 6, process date = 20230314

-- S1. Payment date BEFORE process date (444.44, 20220101)
--     Before: txn 5 | After: txn 6 (moved), not on txn 5
SELECT 'S1 PAST' AS SCENARIO, DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT, PAYMENT_DATE, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL = 2001371316 AND ROUND(AMOUNT,2) = 444.44
ORDER BY TRANSACTION_ID;

-- S2. Payment date AFTER process date (222.22, 20231231)
--     Before: txn 5 | After: txn 6 (moved), not on txn 5
SELECT 'S2 FUTURE' AS SCENARIO, DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT, PAYMENT_DATE, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL = 2001371316 AND ROUND(AMOUNT,2) = 222.22
ORDER BY TRANSACTION_ID;

-- S3. Payment date = process date, MATURITY (111.11, 20230314)  <-- THE FIX
--     Before: txn 5 | After: txn 6 (moved), not on txn 5. (Without fix: 0 rows = fee lost)
SELECT 'S3 SAME-DAY MATURITY' AS SCENARIO, DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT, PAYMENT_DATE, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL = 2001371316 AND ROUND(AMOUNT,2) = 111.11
ORDER BY TRANSACTION_ID;

-- S4. Negative: same-day NON-maturity (type 5, 333.33, 20230314)
--     Before: txn 5 | After: 0 rows (not moved by the fix; removed as before)
SELECT 'S4 SAME-DAY NON-MATURITY' AS SCENARIO, DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT, PAYMENT_DATE, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL = 2001371316 AND ROUND(AMOUNT,2) = 333.33
ORDER BY TRANSACTION_ID;

-- S5. New transaction created (revision happened)
--     Before: txn 5 TERMINATION_LINK null, no txn 6 | After: txn 5 TERMINATION_LINK = 6, txn 6 ORIGINATION_LINK = 5
SELECT 'S5 NEW TXN' AS SCENARIO, DEAL, TRANSACTION_ID, TERMINATION_LINK, ORIGINATION_LINK, ENTRY_DATE
FROM TRADE.TRANSACTION_TABLE
WHERE DEAL = 2001371316 AND TRANSACTION_ID >= 5
ORDER BY TRANSACTION_ID;

-- S6. Transaction map
--     Before: 1 row (version 8 -> txn 5) | After: + row version 9 -> txn 6, TRADE_EVENT AMEND
SELECT 'S6 MAP' AS SCENARIO, TPE_DEAL, TPE_TRANSACTION_ID, OASYS_DEAL, OASYS_TRANSACTION_ID, TRADE_EVENT
FROM TRADE.TPE_DEAL_TRANSACTION_MAP
WHERE OASYS_DEAL = 2001371316
ORDER BY TPE_TRANSACTION_ID;

-- S7. Old txn 5 left with no fees after the move (After: 0 rows)
SELECT 'S7 OLD TXN FEES' AS SCENARIO, DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT, PAYMENT_DATE
FROM TRADE.FEE
WHERE DEAL = 2001371316 AND TRANSACTION_ID = 5;

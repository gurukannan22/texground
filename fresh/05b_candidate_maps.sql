-- Step 5b: Oasys deal / transactions for amend candidates (contracts amended more than once)
-- Good candidate = one OASYS_DEAL with 2+ OASYS_TRANSACTION_IDs (amend created a new txn)
SELECT TPE_DEAL, TPE_TRANSACTION_ID, OASYS_DEAL, OASYS_TRANSACTION_ID, PRODUCT_CLASS, TRADE_EVENT, CREATED_TIME_STAMP
FROM TRADE.TPE_DEAL_TRANSACTION_MAP
WHERE TPE_DEAL IN ('18607953', '18599054', '18596625')
ORDER BY TPE_DEAL, TPE_TRANSACTION_ID;

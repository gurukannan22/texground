-- Step 6: read the key parts of amend message 386121612 (contract 18607953, deal 2001371316)
-- Each column is a ~600-char window around one tag. Copy each cell into Notepad++ to read.
SELECT
  DBMS_LOB.SUBSTR(XML_MESSAGE, 600, GREATEST(DBMS_LOB.INSTR(XML_MESSAGE, 'citimlEventType') - 100, 1))      AS EVENT_TYPE,
  DBMS_LOB.SUBSTR(XML_MESSAGE, 600, GREATEST(DBMS_LOB.INSTR(XML_MESSAGE, 'originatingEvent') - 100, 1))     AS ORIG_EVENT,
  DBMS_LOB.SUBSTR(XML_MESSAGE, 1500, GREATEST(DBMS_LOB.INSTR(XML_MESSAGE, 'versionedTradeId') - 100, 1))    AS TRADE_IDS,
  DBMS_LOB.SUBSTR(XML_MESSAGE, 600, GREATEST(DBMS_LOB.INSTR(XML_MESSAGE, 'premium') - 100, 1))              AS PREMIUM,
  DBMS_LOB.SUBSTR(XML_MESSAGE, 600, GREATEST(DBMS_LOB.INSTR(XML_MESSAGE, 'contractState') - 100, 1))        AS CONTRACT_STATE,
  DBMS_LOB.GETLENGTH(XML_MESSAGE) AS LEN
FROM TRADE.TPE_MESSAGE
WHERE MESSAGE_ID = 386121612;

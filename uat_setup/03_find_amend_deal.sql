-- UAT test deal setup - Step 3 (fast): find deals that already had an AMEND, using the map only (no CLOB scan). Read-only.

-- 3a. Amended FX option (Proteus) trades, single-leg, newest first
SELECT m.OASYS_DEAL, m.OASYS_TRANSACTION_ID, m.TPE_DEAL AS CONTRACT_REF,
       m.TPE_TRANSACTION_ID AS VERSION, m.B2B_LEG_ID, m.TRADE_EVENT, m.CREATED_TIME_STAMP
FROM TRADE.TPE_DEAL_TRANSACTION_MAP m
WHERE m.TRADE_EVENT = 'AMEND'
  AND m.PRODUCT_CLASS = 33
  AND m.TRADE_ENTRY_SYSTEM = 'PROTEUS'
  AND m.CREATED_TIME_STAMP > SYSDATE - 730
  AND ROWNUM <= 30
ORDER BY m.CREATED_TIME_STAMP DESC;

-- 3b. If 3a is empty: what TRADE_EVENT values exist for FX options in UAT?
SELECT TRADE_EVENT, COUNT(*) AS CNT
FROM TRADE.TPE_DEAL_TRANSACTION_MAP
WHERE PRODUCT_CLASS = 33
  AND TRADE_ENTRY_SYSTEM = 'PROTEUS'
GROUP BY TRADE_EVENT
ORDER BY CNT DESC;

-- UAT test deal setup - Step 4: inspect candidate deal 2002739527 (contract 16082182, single leg). Read-only.

-- 4a. Transactions
SELECT DEAL, TRANSACTION_ID, TERMINATION_LINK, ORIGINATION_LINK, ENTRY_DATE
FROM TRADE.TRANSACTION_TABLE
WHERE DEAL = 2002739527
ORDER BY TRANSACTION_ID;

-- 4b. Fees
SELECT DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT,
       PAYMENT_DATE, CURRENCY, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL = 2002739527
ORDER BY TRANSACTION_ID, FEE_NUMBER;

-- 4c. Map history (all versions / events)
SELECT TPE_DEAL, TPE_TRANSACTION_ID AS VERSION, OASYS_TRANSACTION_ID, B2B_LEG_ID,
       GROUP_ID, TRADE_EVENT, CREATED_TIME_STAMP
FROM TRADE.TPE_DEAL_TRANSACTION_MAP
WHERE OASYS_DEAL = 2002739527
ORDER BY CREATED_TIME_STAMP;

-- 4d. Messages for the contract (CLOB check is limited to this one contract, so it is fast)
SELECT MESSAGE_ID, STATUS, LAST_UPDATED_TIME_STAMP,
       DBMS_LOB.SUBSTR(XML_MESSAGE, 120, GREATEST(DBMS_LOB.INSTR(XML_MESSAGE, 'citimlEventType>') , 1)) AS EVENT_TXT,
       DBMS_LOB.INSTR(XML_MESSAGE, 'termDeposit') AS TD,
       DBMS_LOB.INSTR(XML_MESSAGE, 'TRS_Terms')   AS TRS,
       DBMS_LOB.INSTR(XML_MESSAGE, 'CTLON')       AS LDN,
       DBMS_LOB.INSTR(XML_MESSAGE, 'CTNY')        AS NY
FROM TRADE.TPE_MESSAGE
WHERE CONTRACT_REF = '16082182'
ORDER BY MESSAGE_ID;

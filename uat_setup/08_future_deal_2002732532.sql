-- UAT future-dated test - candidate deal 2002732532 (contract 24201656, latest txn 3). Read-only.
-- UAT process date = 20260306. Txn 3 has future maturity fee 53997.84 (20260406).

-- 8a. Transactions (expect latest = txn 3)
SELECT DEAL, TRANSACTION_ID, TERMINATION_LINK, ORIGINATION_LINK, ENTRY_DATE
FROM TRADE.TRANSACTION_TABLE
WHERE DEAL = 2002732532
ORDER BY TRANSACTION_ID;

-- 8b. Fees
SELECT DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT,
       PAYMENT_DATE, CURRENCY, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL = 2002732532
ORDER BY TRANSACTION_ID, FEE_NUMBER;

-- 8c. Map history (highest VERSION for contract 24201656, and which txn it maps to)
SELECT TPE_DEAL, TPE_TRANSACTION_ID AS VERSION, OASYS_TRANSACTION_ID, B2B_LEG_ID,
       GROUP_ID, PRODUCT_CLASS, TRADE_ENTRY_SYSTEM, TRADE_EVENT, CREATED_TIME_STAMP
FROM TRADE.TPE_DEAL_TRANSACTION_MAP
WHERE OASYS_DEAL = 2002732532
ORDER BY CREATED_TIME_STAMP;

-- 8d. Messages for contract 24201656
--     Need: AMEND > 0, TD = 0, TRS = 0, LDN or NY > 0, VERSION_TXT >= highest VERSION in 8c
SELECT MESSAGE_ID, STATUS, LAST_UPDATED_TIME_STAMP,
       DBMS_LOB.INSTR(XML_MESSAGE, 'citimlEventType>Amend') AS AMEND,
       DBMS_LOB.INSTR(XML_MESSAGE, 'termDeposit')           AS TD,
       DBMS_LOB.INSTR(XML_MESSAGE, 'TRS_Terms')             AS TRS,
       DBMS_LOB.INSTR(XML_MESSAGE, 'CTLON')                 AS LDN,
       DBMS_LOB.INSTR(XML_MESSAGE, 'CTNY')                  AS NY,
       DBMS_LOB.SUBSTR(XML_MESSAGE, 40, DBMS_LOB.INSTR(XML_MESSAGE, '<fpml:version>')) AS VERSION_TXT
FROM TRADE.TPE_MESSAGE
WHERE CONTRACT_REF = '24201656'
ORDER BY MESSAGE_ID;

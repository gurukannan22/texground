-- UAT test deal setup - Step 1: read-only checks on candidate deals
-- Connect to the UAT DB (OASYSU7) before running.

-- 1a. Transactions per deal (which txn is latest, how many revisions)
SELECT DEAL, TRANSACTION_ID, TERMINATION_LINK, ORIGINATION_LINK, ENTRY_DATE
FROM TRADE.TRANSACTION_TABLE
WHERE DEAL IN (1253439971, 2002738453, 2002738461)
ORDER BY DEAL, TRANSACTION_ID;

-- 1b. Fees per deal
SELECT DEAL, TRANSACTION_ID, FEE_NUMBER, TYPE, ROUND(AMOUNT,2) AS AMOUNT,
       PAYMENT_DATE, CURRENCY, DESCRIPTION
FROM TRADE.FEE
WHERE DEAL IN (1253439971, 2002738453, 2002738461)
ORDER BY DEAL, TRANSACTION_ID, FEE_NUMBER;

-- 1c. Map rows (product class, source system, stored version)
SELECT OASYS_DEAL, OASYS_TRANSACTION_ID, TPE_DEAL, TPE_TRANSACTION_ID,
       PRODUCT_CLASS, TRADE_ENTRY_SYSTEM, TRADE_EVENT, GROUP_ID
FROM TRADE.TPE_DEAL_TRANSACTION_MAP
WHERE OASYS_DEAL IN (1253439971, 2002738453, 2002738461)
ORDER BY OASYS_DEAL, CREATED_TIME_STAMP;

-- 1d. UAT process date and feature flag
SELECT * FROM REFERENCE_DATA.PROCESS_DATE;

SELECT TYPE, CODE, EXTERNAL_CODE FROM REFERENCE_DATA.CODE
WHERE TYPE = 'SAME_DAY_FEE_MIG_C263_119169';
